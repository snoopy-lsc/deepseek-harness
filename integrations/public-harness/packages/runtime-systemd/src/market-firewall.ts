/** Separately loaded `inet dsh_market` table: listener cgroup drop + owner set; never part of network.install. */
import { validatePortRange, type PortRange } from '@public-harness/contracts'

/** The only nftables table that holds market port drops; host and per-instance tables are never touched. */
export const MARKET_TABLE = 'dsh_market'

/** Listening sockets' cgroup as measured (or configured); the loader renders whatever string it is given. */
export interface MarketListenerCgroup {
  readonly path: string
  readonly level: number
}

/** Installed ruleset file that `load-dsh-market.sh` loads (rendered by `render-market-firewall.ts`). */
export const DEFAULT_MARKET_RULES_PATH = '/etc/dsh-public/dsh-market.nft'

/** Candidate listener cgroup until P0.8 measures it: the socket unit's own cgroup (level 2). P0.8 may show
 * `init.scope` (level 1) instead; the renderer takes `--listener-cgroup` so the measured value can be installed. */
export const DEFAULT_MARKET_LISTENER_CGROUP: MarketListenerCgroup = { path: 'system.slice/dsh-plugins.socket', level: 2 }

const CGROUP_SEGMENT = /^[A-Za-z0-9@_.:-]{1,255}$/

/** Validate a cgroup path relative to the cgroup2 root (`system.slice/dsh-plugins.socket`) and derive its level.
 * Quotes, backslashes, `..`, empty segments and leading slashes are refused so the path is safe inside an nft string.
 * @param path Relative cgroup path.
 * @returns Path and level (number of segments).
 */
export function parseMarketListenerCgroup(path: string): MarketListenerCgroup {
  if (typeof path !== 'string' || path.length === 0 || path.length > 1024) throw new Error('listener cgroup must be a non-empty relative path')
  const segments = path.split('/')
  if (segments.some(segment => !CGROUP_SEGMENT.test(segment) || segment === '.' || segment === '..')) {
    throw new Error('listener cgroup must be a relative cgroup2 path of plain segments')
  }
  return { path, level: segments.length }
}

/** Inputs for the socket-unit loader script. */
export interface MarketFirewallOptions {
  readonly marketPorts: PortRange
  readonly listenerCgroup: MarketListenerCgroup
}

/** One `plugin_endpoint` row as a uid/port pair for the `market_owner` set. */
export interface MarketEndpoint {
  readonly uid: number
  readonly port: number
}

/** Inclusive port range as an nft define / dport expression (`min-max`). */
export function formatMarketPorts(range: PortRange): string {
  return `${range.min}-${range.max}`
}

/**
 * Loader script for `dsh-plugins.socket` ExecStartPost: create table and set if absent, flush and refill
 * only the chains so `market_owner` elements survive a reload. Outside `network.install`.
 */
export function renderMarketTable(options: MarketFirewallOptions): string {
  const ports = formatMarketPorts(validatePortRange(options.marketPorts, 'ports.market'))
  const { path, level } = options.listenerCgroup
  if (parseMarketListenerCgroup(path).level !== level) throw new Error('listener cgroup level must equal its number of path segments')
  return [
    `define MARKET_PORTS = ${ports}`,
    `add table inet ${MARKET_TABLE}`,
    `add set inet ${MARKET_TABLE} market_owner { type mark . inet_service ; }`,
    `add chain inet ${MARKET_TABLE} input { type filter hook input priority filter - 2 ; policy accept ; }`,
    `add chain inet ${MARKET_TABLE} market_listener`,
    `flush chain inet ${MARKET_TABLE} input`,
    `flush chain inet ${MARKET_TABLE} market_listener`,
    `add rule inet ${MARKET_TABLE} input iif "lo" tcp dport $MARKET_PORTS jump market_listener`,
    `add rule inet ${MARKET_TABLE} input iif "lo" tcp dport $MARKET_PORTS ct mark . tcp dport != @market_owner drop`,
    `add rule inet ${MARKET_TABLE} market_listener socket cgroupv2 level ${level} "${path}" return`,
    `add rule inet ${MARKET_TABLE} market_listener drop`,
    '',
  ].join('\n')
}

/** Installed ruleset file text: a do-not-edit header plus {@link renderMarketTable}. The loader accepts only lines of
 * this shape (comments, the one `define`, and `add`/`flush` statements on `inet dsh_market`).
 * @param options Market range and measured listener cgroup.
 * @returns nft script text for `nft -f`.
 */
export function renderMarketRulesFile(options: MarketFirewallOptions): string {
  return [
    '#!/usr/sbin/nft -f',
    '# Generated by deploy/native/scripts/render-market-firewall.ts from ports.market; do not edit.',
    '# Loaded atomically by /usr/lib/dsh-public/load-dsh-market.sh (dsh-plugins.socket ExecStartPost, fatal).',
    '# Chains are flushed and refilled; the market_owner set keeps its elements across reloads.',
    renderMarketTable(options),
  ].join('\n')
}

/** Statement shapes `load-dsh-market.sh` accepts; anything else (another table, `flush ruleset`, `delete`, `include`)
 * is refused so the loader can never change rules outside `inet dsh_market`. Kept in step with the shell allowlist. */
export const MARKET_RULE_LINE = /^(?:#.*|define MARKET_PORTS = \d{1,5}-\d{1,5}|(?:add|flush) (?:table|set|chain|rule) inet dsh_market(?: .*)?)$/

/** Check an installed ruleset file the way the loader and the preflight do.
 * @param text File contents.
 * @param marketPorts Expected `ports.market`, when known.
 * @returns Problems found; empty when the file is acceptable.
 */
export function checkMarketRulesFile(text: string, marketPorts?: PortRange): string[] {
  const problems: string[] = []
  const lines = text.split('\n').filter(line => line.trim().length > 0)
  const bad = lines.filter(line => !MARKET_RULE_LINE.test(line))
  if (bad.length > 0) problems.push(`${bad.length} line(s) outside inet ${MARKET_TABLE}`)
  const defines = lines.filter(line => line.startsWith('define MARKET_PORTS = '))
  if (defines.length !== 1) problems.push('exactly one MARKET_PORTS define is required')
  else if (marketPorts !== undefined && defines[0] !== `define MARKET_PORTS = ${formatMarketPorts(marketPorts)}`) problems.push('MARKET_PORTS differs from ports.market')
  for (const required of [
    `add set inet ${MARKET_TABLE} market_owner { type mark . inet_service ; }`,
    `add rule inet ${MARKET_TABLE} input iif "lo" tcp dport $MARKET_PORTS jump market_listener`,
    `add rule inet ${MARKET_TABLE} input iif "lo" tcp dport $MARKET_PORTS ct mark . tcp dport != @market_owner drop`,
    `add rule inet ${MARKET_TABLE} market_listener drop`,
  ]) if (!lines.includes(required)) problems.push(`missing: ${required}`)
  if (!lines.some(line => /^add rule inet dsh_market market_listener socket cgroupv2 level \d+ "[^"]+" return$/.test(line))) problems.push('missing the listener cgroup return rule')
  return problems
}

/** `nft` argv adding or deleting `market_owner` pairs in one command (no shell, no temporary file).
 * @param op `add` or `delete`.
 * @param rows uid/port pairs; must be non-empty.
 */
export function marketOwnerArgv(op: 'add' | 'delete', rows: readonly MarketEndpoint[]): string[] {
  if (rows.length === 0) throw new Error('no market_owner elements')
  for (const row of rows) {
    if (!Number.isSafeInteger(row.uid) || row.uid <= 0 || !Number.isSafeInteger(row.port) || row.port < 1 || row.port > 65_535) throw new Error('invalid market_owner element')
  }
  return [op, 'element', 'inet', MARKET_TABLE, 'market_owner', `{ ${rows.map(row => `${row.uid} . ${row.port}`).join(', ')} }`]
}

/** Add one owner pair; callers run this under the same provisioner lock as the probe. */
export function renderMarketOwnerAdd(uid: number, port: number): string {
  return `add element inet ${MARKET_TABLE} market_owner { ${uid} . ${port} }`
}

/** Delete one owner pair (stale element or endpoint row removal). */
export function renderMarketOwnerDelete(uid: number, port: number): string {
  return `delete element inet ${MARKET_TABLE} market_owner { ${uid} . ${port} }`
}

/** Parse `nft list set inet dsh_market market_owner` (or list table) stdout into uid/port pairs. */
export function parseMarketOwnerElements(output: string): MarketEndpoint[] {
  const match = /elements\s*=\s*\{\s*([^}]*)\}/s.exec(output)
  if (match === null) return []
  const body = match[1]!.trim()
  if (body.length === 0) return []
  const rows: MarketEndpoint[] = []
  for (const part of body.split(',')) {
    // `nft list set` prints a mark key in hex (`0x000004b1 . 31000`); accept decimal too.
    const pair = /^\s*(0x[0-9a-fA-F]+|\d+)\s*\.\s*(\d+)\s*$/.exec(part)
    if (pair === null) continue
    rows.push({ uid: Number(pair[1]), port: Number(pair[2]) })
  }
  return rows
}

/** Stable key for set equality (`uid.port`). */
export function marketEndpointKey(row: MarketEndpoint): string {
  return `${row.uid}.${row.port}`
}
