/** The model used by the compiler. Production calls the Anthropic-style Messages API through a quota job channel, so personal
 * allowances, the site allowance and the over-limit policy apply unchanged; tests and the demo use the deterministic mock. */

/** What the compiler asks. `task` and `input` let the mock answer without parsing prompts; real models only read the prompts. */
export interface ModelRequest {
  readonly task: 'extract' | 'write' | 'lint'
  readonly system: string
  readonly prompt: string
  readonly maxTokens: number
  readonly input?: unknown
}
export interface ModelReply { readonly text: string; readonly inputTokens: number; readonly outputTokens: number }
export interface KbModel { complete(request: ModelRequest): Promise<ModelReply> }

/** The model refused or failed; `status` is the quota proxy's HTTP status (402 when the allowance is spent). */
export class ModelError extends Error {
  readonly status: number
  constructor(status: number, message: string) { super(message); this.status = status }
}

/** A Messages API client against one quota job channel.
 * @param options Base URL ending in `/v1`, a credential source, the platform model ID and an optional fetch.
 * @returns Model.
 */
export function createMessagesModel(options: { baseUrl: string; credential: () => Promise<string>; model: string; fetcher?: typeof fetch }): KbModel {
  const fetcher = options.fetcher ?? globalThis.fetch
  return {
    async complete(request) {
      const reply = await fetcher(`${options.baseUrl}/messages`, {
        method: 'POST',
        headers: { 'content-type': 'application/json', authorization: `Bearer ${await options.credential()}`, 'anthropic-version': '2023-06-01' },
        body: JSON.stringify({ model: options.model, max_tokens: request.maxTokens, stream: true, system: request.system,
          messages: [{ role: 'user', content: request.prompt }] }),
      })
      if (!reply.ok || reply.body === null) throw new ModelError(reply.status, `model call failed (${reply.status})`)
      let text = '', inputTokens = 0, outputTokens = 0, buffer = ''
      const decoder = new TextDecoder()
      const handle = (data: string) => {
        let event: Record<string, any>
        try { event = JSON.parse(data) as Record<string, any> } catch { return }
        if (event.type === 'message_start') { inputTokens = Number(event.message?.usage?.input_tokens ?? 0); outputTokens = Number(event.message?.usage?.output_tokens ?? 0) }
        else if (event.type === 'content_block_delta' && event.delta?.type === 'text_delta') text += String(event.delta.text ?? '')
        else if (event.type === 'message_delta' && event.usage?.output_tokens !== undefined) outputTokens = Number(event.usage.output_tokens)
        else if (event.type === 'error') throw new ModelError(502, 'model stream error')
      }
      for await (const chunk of reply.body as unknown as AsyncIterable<Uint8Array>) {
        buffer += decoder.decode(chunk, { stream: true })
        let index
        while ((index = buffer.indexOf('\n\n')) !== -1) {
          const block = buffer.slice(0, index); buffer = buffer.slice(index + 2)
          for (const line of block.split('\n')) if (line.startsWith('data:')) handle(line.slice(5).trim())
        }
      }
      return { text, inputTokens, outputTokens }
    },
  }
}

const words = (text: string) => Math.max(1, Math.ceil(text.length / 4))
/** Deterministic stand-in for the model. Pages it writes say they are demo content when `demo` is set. */
export function createMockModel(options: { demo?: boolean } = {}): KbModel & { calls: ModelRequest[] } {
  const calls: ModelRequest[] = []
  return {
    calls,
    async complete(request) {
      calls.push(request)
      let text: string
      if (request.task === 'extract') {
        const input = request.input as { path: string; text: string }
        const headings = [...input.text.matchAll(/^#{1,3}\s+(.+)$/gm)].map(match => match[1]!.trim()).slice(0, 6)
        const titles = headings.length > 0 ? headings : [input.path.replace(/^raw\//, '').replace(/\.[^.]+$/, '')]
        const sentences = input.text.replace(/^#.*$/gm, '').split(/(?<=[.!?。！？])\s+/).map(s => s.trim()).filter(Boolean)
        text = JSON.stringify({ concepts: titles.map((title, index) => ({ title, summary: sentences[index] ?? `Notes about ${title}.`, claims: sentences.slice(index, index + 2) })) })
      } else if (request.task === 'write') {
        const input = request.input as { title: string; summary: string; claims: Array<{ text: string; source: string }>; related: string[] }
        const lines = [`# ${input.title}`, '', options.demo ? '> Demo content generated by the mock compiler; not written by a model.\n' : '', input.summary, '', '## Key points', '',
          ...input.claims.map(claim => `- ${claim.text} (source: ${claim.source})`), '']
        if (input.related.length > 0) lines.push('## Related', '', ...input.related.map(slug => `- [${slug}](${slug}.md)`), '')
        text = lines.filter((line, index) => line !== '' || lines[index - 1] !== '').join('\n')
      } else text = 'No contradictions found.'
      return { text, inputTokens: words(request.system) + words(request.prompt), outputTokens: words(text) }
    },
  }
}
